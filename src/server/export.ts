type ExportRow = Record<(typeof COLUMNS)[number]["key"], string | number>;

export async function fetchExportRows(filters: VehicleFilters, limit: number) {
  const where = buildWhere(filters);
  const [total, vehicles] = await Promise.all([
    prisma.vehicle.count({ where }),
    prisma.vehicle.findMany({
      where,
      orderBy: buildOrderBy(filters),
      take: limit,
      include: { manufacturer: true, model: true, area: true },
    }),
  ]);
  const rows: ExportRow[] = vehicles.map((v) => ({
    vehicleId: formatVehicleId(v.vehicleNo),
    registrationNumber: v.registrationNumber,
    category: CATEGORY_LABELS[v.category],
    manufacturer: v.manufacturer.name,
    model: v.model.name,
    variant: v.variant ?? "",
    manufacturingYear: v.manufacturingYear ?? "",
    registrationYear: v.registrationYear ?? "",
    registrationDate: v.registrationDate ? v.registrationDate.toISOString().slice(0, 10) : "",
    engineCapacityCc: v.engineCapacityCc ?? "",
    fuelType: v.fuelType ? FUEL_LABELS[v.fuelType] : "",
    transmission: v.transmission ? TRANSMISSION_LABELS[v.transmission] : "",
    color: v.color ?? "",
    bodyType: v.bodyType ?? "",
    district: v.district ? DISTRICT_LABELS[v.district] : "",
    area: v.area?.name ?? "",
    status: STATUS_LABELS[v.status],
    dataSource: v.dataSource,
    createdAt: v.createdAt.toISOString(),
    updatedAt: v.updatedAt.toISOString(),
  }));
  return { total, rows };
}

export function toCsv(rows: ExportRow[]) {
  return (
    "﻿" +
    Papa.unparse({
      fields: COLUMNS.map((c) => c.header),
      data: rows.map((r) => COLUMNS.map((c) => r[c.key])),
    })
  );
}

export async function toXlsx(rows: ExportRow[], meta: { generatedBy: string; filterSummary: string; total: number }) {
  const wb = new ExcelJS.Workbook();
  wb.creator = BRAND.name;
  wb.created = new Date();
  const ws = wb.addWorksheet("Vehicles", { views: [{ state: "frozen", ySplit: 1 }] });
  ws.columns = COLUMNS.map((c) => ({ header: c.header, key: c.key, width: c.width }));
  ws.addRows(rows);
  const header = ws.getRow(1);
  header.font = { bold: true, color: { argb: "FFFFFFFF" } };
  header.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF0B1F4B" } };
  header.alignment = { vertical: "middle" };
  header.height = 22;
  ws.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: COLUMNS.length } };

  const info = wb.addWorksheet("Report Info");
  info.columns = [{ width: 24 }, { width: 80 }];
  info.addRows([
    ["Report", `${BRAND.name} — Vehicle Export`],
    ["Generated", formatDateTime(new Date())],
    ["Generated by", meta.generatedBy],
    ["Filters", meta.filterSummary || "None (all records)"],
    ["Matching records", meta.total],
    ["Rows in this file", rows.length],
    ["Note", "All figures are derived from records held in the SKA-VI database at export time."],
  ]);
  info.getColumn(1).font = { bold: true };
  return Buffer.from(await wb.xlsx.writeBuffer());
}

export async function toPdf(rows: ExportRow[], meta: { generatedBy: string; filterSummary: string; total: number; summary: { label: string; value: string }[] }) {
  const doc = new PDFDocument({ size: "A4", layout: "landscape", margin: 36, bufferPages: true, info: { Title: `${BRAND.short} Vehicle Report`, Author: BRAND.name } });
  const chunks: Buffer[] = [];
  doc.on("data", (c: Buffer) => chunks.push(c));
  const done = new Promise<Buffer>((resolve) => doc.on("end", () => resolve(Buffer.concat(chunks))));

  const navy = "#0B1F4B";
  const blue = "#2563EB";
  const pageW = doc.page.width;
  const left = 36;
  const usable = pageW - 72;

  // Header band
  doc.rect(0, 0, pageW, 70).fill(navy);
  doc.fillColor("#FFFFFF").font("Helvetica-Bold").fontSize(18).text(BRAND.name, left, 18);
  doc.font("Helvetica").fontSize(9).fillColor("#BFD3FF").text(`${BRAND.description} · ${BRAND.tagline}`, left, 42);
  doc.fillColor("#FFFFFF").fontSize(9).text(`Generated ${formatDateTime(new Date())}`, left, 22, { width: usable, align: "right" });
  doc.text(`By ${meta.generatedBy}`, left, 36, { width: usable, align: "right" });

  doc.fillColor(navy).font("Helvetica-Bold").fontSize(13).text("Vehicle Records Report", left, 88);
  doc.font("Helvetica").fontSize(9).fillColor("#475569").text(`Filters: ${meta.filterSummary || "None (all records)"}`, left, 106, { width: usable });

  // Summary tiles
  let x = left;
  const tileW = Math.min(150, (usable - 10 * (meta.summary.length - 1)) / Math.max(1, meta.summary.length));
  const y0 = 126;
  for (const s of meta.summary) {
    doc.roundedRect(x, y0, tileW, 44, 4).fillAndStroke("#F1F5FB", "#D6E0F0");
    doc.fillColor("#64748B").fontSize(7.5).text(s.label.toUpperCase(), x + 8, y0 + 8, { width: tileW - 16 });
    doc.fillColor(navy).font("Helvetica-Bold").fontSize(13).text(s.value, x + 8, y0 + 20, { width: tileW - 16 });
    doc.font("Helvetica");
    x += tileW + 10;
  }

  // Table
  const cols = [
    { key: "vehicleId", header: "Vehicle ID", w: 62 },
    { key: "registrationNumber", header: "Reg. No.", w: 66 },
    { key: "category", header: "Category", w: 66 },
    { key: "manufacturer", header: "Manufacturer", w: 70 },
    { key: "model", header: "Model", w: 70 },
    { key: "manufacturingYear", header: "Mfg", w: 32 },
    { key: "registrationYear", header: "Reg", w: 32 },
    { key: "engineCapacityCc", header: "CC", w: 36 },
    { key: "fuelType", header: "Fuel", w: 44 },
    { key: "color", header: "Color", w: 48 },
    { key: "district", header: "District", w: 70 },
    { key: "area", header: "Area", w: 72 },
    { key: "status", header: "Status", w: 0 },
  ] as const;
  const fixed = cols.reduce((a, c) => a + c.w, 0);
  const widths = cols.map((c) => (c.w === 0 ? usable - fixed : c.w));
  const rowH = 15;
  let y = y0 + 60;

  const drawHeader = () => {
    doc.rect(left, y, usable, rowH + 2).fill(navy);
    let cx = left;
    doc.font("Helvetica-Bold").fontSize(7.5).fillColor("#FFFFFF");
    cols.forEach((c, i) => {
      doc.text(c.header, cx + 4, y + 5, { width: widths[i] - 8, lineBreak: false, ellipsis: true });
      cx += widths[i];
    });
    y += rowH + 2;
    doc.font("Helvetica").fillColor("#0F172A");
  };
  drawHeader();
  rows.forEach((r, idx) => {
    if (y + rowH > doc.page.height - 40) {
      doc.addPage();
      y = 36;
      drawHeader();
    }
    if (idx % 2 === 1) doc.rect(left, y, usable, rowH).fill("#F5F8FD");
    let cx = left;
    doc.fontSize(7.5).fillColor("#0F172A");
    cols.forEach((c, i) => {
      doc.text(String(r[c.key] ?? ""), cx + 4, y + 4, { width: widths[i] - 8, lineBreak: false, ellipsis: true });
      cx += widths[i];
    });
    y += rowH;
  });
  if (!rows.length) {
    doc.fontSize(10).fillColor("#64748B").text("No records match the selected filters.", left, y + 12);
  } else if (meta.total > rows.length) {
    doc.fontSize(8).fillColor(blue).text(`Showing first ${rows.length} of ${meta.total} matching records. Use CSV or Excel export for the full dataset.`, left, y + 8);
  }

  // Footer on every page
  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    doc.fontSize(7).fillColor("#94A3B8").text(
      `${BRAND.short} · Confidential · Figures derived from records in the SKA-VI database · Page ${i + 1} of ${range.count}`,
      left,
      doc.page.height - 26,
      { width: usable, align: "center", lineBreak: false },
    );
  }
  doc.end();
  return done;
}

export function describeFilters(f: VehicleFilters) {
  const parts: string[] = [];
  if (f.q) parts.push(`Search "${f.q}"`);
  if (f.reg) parts.push(`Reg. no. contains "${f.reg}"`);
  if (f.manufacturer) parts.push(`Manufacturer "${f.manufacturer}"`);
  if (f.model) parts.push(`Model "${f.model}"`);
  if (f.category?.length) parts.push(`Category: ${f.category.map((c) => CATEGORY_LABELS[c as keyof typeof CATEGORY_LABELS]).join(", ")}`);
  if (f.fuel?.length) parts.push(`Fuel: ${f.fuel.map((c) => FUEL_LABELS[c as keyof typeof FUEL_LABELS]).join(", ")}`);
  if (f.transmission) parts.push(`Transmission: ${TRANSMISSION_LABELS[f.transmission as keyof typeof TRANSMISSION_LABELS]}`);
  if (f.status) parts.push(`Status: ${STATUS_LABELS[f.status as keyof typeof STATUS_LABELS]}`);
  if (f.color) parts.push(`Color "${f.color}"`);
  if (f.district?.length) parts.push(`District: ${f.district.map((d) => DISTRICT_LABELS[d as keyof typeof DISTRICT_LABELS]).join(", ")}`);
  if (f.area) parts.push(`Area "${f.area}"`);
  if (f.yearFrom || f.yearTo) parts.push(`Mfg. year ${f.yearFrom ?? "…"}–${f.yearTo ?? "…"}`);
  if (f.regYearFrom || f.regYearTo) parts.push(`Reg. year ${f.regYearFrom ?? "…"}–${f.regYearTo ?? "…"}`);
  if (f.ccMin || f.ccMax) parts.push(`Engine ${f.ccMin ?? "…"}–${f.ccMax ?? "…"} cc`);
  if (f.source) parts.push(`Source "${f.source}"`);
  return parts.join("; ");
}

